-- EZP Smart Parking schema
-- Purpose:
-- 1. Register users with Supabase Auth
-- 2. Store each user's cars
-- 3. Let users book a parking slot for a time range
-- 4. Keep parking slot structure separate from sensor/event data

create extension if not exists "pgcrypto";
create extension if not exists "btree_gist";

-- Optional cleanup if you want to replace the old raw tables from the screenshot.
drop table if exists public.parking_floor1;
drop table if exists public.parking_floor2;

do $$
begin
  if not exists (select 1 from pg_type where typname = 'booking_status') then
    create type public.booking_status as enum (
      'booked',
      'checked_in',
      'completed',
      'cancelled',
      'expired'
    );
  end if;
end
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.parking_floors (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.parking_slots (
  id bigint generated by default as identity primary key,
  floor_id bigint not null references public.parking_floors(id) on delete cascade,
  code text not null unique,
  slot_number int not null,
  is_reservable boolean not null default true,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (floor_id, slot_number)
);

create table if not exists public.vehicle_registrations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  plate_number text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  constraint vehicle_plate_format check (char_length(trim(plate_number)) >= 3),
  unique (user_id, plate_number)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  vehicle_id uuid not null references public.vehicle_registrations(id) on delete cascade,
  slot_id bigint not null references public.parking_slots(id) on delete cascade,
  start_time timestamptz not null,
  end_time timestamptz not null,
  status public.booking_status not null default 'booked',
  created_at timestamptz not null default now(),
  constraint booking_time_valid check (end_time > start_time)
);

create table if not exists public.parking_events (
  id bigint generated by default as identity primary key,
  slot_id bigint not null references public.parking_slots(id) on delete cascade,
  event_type text not null check (event_type in ('enter', 'exit', 'sensor_update')),
  event_status text,
  created_at timestamptz not null default now()
);

create index if not exists idx_vehicle_registrations_user_id
  on public.vehicle_registrations(user_id);

create index if not exists idx_bookings_user_id
  on public.bookings(user_id);

create index if not exists idx_bookings_slot_id
  on public.bookings(slot_id);

create index if not exists idx_bookings_time_range
  on public.bookings(start_time, end_time);

alter table public.bookings
  drop constraint if exists bookings_no_overlap;

alter table public.bookings
  add constraint bookings_no_overlap
  exclude using gist (
    slot_id with =,
    tstzrange(start_time, end_time, '[)') with &&
  )
  where (status in ('booked', 'checked_in'));

