drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own"
  on public.profiles
  for select
  using (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
  on public.profiles
  for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

drop policy if exists "public_read_floors" on public.parking_floors;
create policy "public_read_floors"
  on public.parking_floors
  for select
  using (true);

drop policy if exists "public_read_slots" on public.parking_slots;
create policy "public_read_slots"
  on public.parking_slots
  for select
  using (true);

drop policy if exists "users_manage_own_vehicles" on public.vehicle_registrations;
create policy "users_manage_own_vehicles"
  on public.vehicle_registrations
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "users_manage_own_bookings" on public.bookings;
create policy "users_manage_own_bookings"
  on public.bookings
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "authenticated_read_events" on public.parking_events;
create policy "authenticated_read_events"
  on public.parking_events
  for select
  using (auth.role() = 'authenticated');

create or replace view public.booking_overview as
select
  b.id,
  b.user_id,
  v.plate_number,
  s.code as slot_code,
  f.code as floor_code,
  f.name as floor_name,
  b.start_time,
  b.end_time,
  b.status,
  b.created_at
from public.bookings b
join public.vehicle_registrations v on v.id = b.vehicle_id
join public.parking_slots s on s.id = b.slot_id
join public.parking_floors f on f.id = s.floor_id;
