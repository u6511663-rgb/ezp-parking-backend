create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id)
  values (new.id)
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.create_booking(
  p_vehicle_id uuid,
  p_slot_id bigint,
  p_start_time timestamptz,
  p_end_time timestamptz
)
returns public.bookings
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_booking public.bookings;
  v_vehicle_owner uuid;
  v_slot_reservable boolean;
begin
  if v_user_id is null then
    raise exception 'AUTH_REQUIRED' using errcode = 'P0001';
  end if;

  if p_end_time <= p_start_time then
    raise exception 'INVALID_TIME_RANGE' using errcode = 'P0001';
  end if;

  select user_id into v_vehicle_owner
  from public.vehicle_registrations
  where id = p_vehicle_id;

  if v_vehicle_owner is distinct from v_user_id then
    raise exception 'VEHICLE_NOT_OWNED_BY_USER' using errcode = 'P0001';
  end if;

  select is_reservable into v_slot_reservable
  from public.parking_slots
  where id = p_slot_id
    and is_active = true;

  if v_slot_reservable is not true then
    raise exception 'SLOT_NOT_AVAILABLE_FOR_BOOKING' using errcode = 'P0001';
  end if;

  insert into public.bookings (
    user_id,
    vehicle_id,
    slot_id,
    start_time,
    end_time
  )
  values (
    v_user_id,
    p_vehicle_id,
    p_slot_id,
    p_start_time,
    p_end_time
  )
  returning * into v_booking;

  return v_booking;
exception
  when exclusion_violation then
    raise exception 'SLOT_ALREADY_BOOKED' using errcode = 'P0001';
end;
$$;

grant execute on function public.create_booking(uuid, bigint, timestamptz, timestamptz)
  to authenticated;

