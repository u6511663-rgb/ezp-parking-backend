-- Keeps parking_floor1 and parking_floor2
-- Adds user profile, car registration, booking storage
-- Booking is allowed only for floor 2 because floor 2 has the barrier

create extension if not exists "pgcrypto";

-- =========================
-- USER PROFILE
-- =========================

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email)
  on conflict (id) do update
    set email = excluded.email;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- =========================
-- YOUR CURRENT FLOOR TABLES
-- =========================

create table if not exists public.parking_floor1 (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  slot int8 not null check (slot between 1 and 3),
  status text not null check (status in ('empty', 'occupied'))
);

create table if not exists public.parking_floor2 (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  slot int8 not null check (slot between 1 and 3),
  status text not null check (status in ('empty', 'occupied'))
);

-- =========================
-- USER CARS
-- =========================

create table if not exists public.vehicle_registrations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  plate_number text not null,
  created_at timestamptz not null default now(),
  unique (user_id, plate_number)
);

-- =========================
-- USER BOOKINGS
-- =========================

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  vehicle_id uuid not null references public.vehicle_registrations(id) on delete cascade,
  floor_no int not null check (floor_no = 2),
  slot int not null check (slot between 1 and 3),
  start_time timestamptz not null,
  end_time timestamptz not null,
  status text not null default 'booked' check (status in ('booked', 'checked_in', 'completed', 'cancelled', 'expired')),
  created_at timestamptz not null default now(),
  constraint booking_time_valid check (end_time > start_time)
);

create index if not exists idx_vehicle_registrations_user_id
  on public.vehicle_registrations(user_id);

create index if not exists idx_bookings_user_id
  on public.bookings(user_id);

create index if not exists idx_bookings_floor_slot
  on public.bookings(floor_no, slot);

-- =========================
-- OPTIONAL VIEW FOR APP
-- =========================

create or replace view public.booking_overview as
select
  b.id,
  b.user_id,
  p.email,
  v.plate_number,
  b.floor_no,
  b.slot,
  b.start_time,
  b.end_time,
  b.status,
  b.created_at
from public.bookings b
join public.vehicle_registrations v on v.id = b.vehicle_id
left join public.profiles p on p.id = b.user_id;

