-- =========================
-- HELPER FUNCTION TO CREATE BOOKING
-- =========================

create or replace function public.create_booking(
  p_vehicle_id uuid,
  p_floor_no int,
  p_slot int,
  p_start_time timestamptz,
  p_end_time timestamptz
)
returns public.bookings
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_owner uuid;
  v_booking public.bookings;
  v_conflict_count int;
begin
  if v_user_id is null then
    raise exception 'AUTH_REQUIRED' using errcode = 'P0001';
  end if;

  if p_end_time <= p_start_time then
    raise exception 'INVALID_TIME_RANGE' using errcode = 'P0001';
  end if;

  if p_floor_no <> 2 then
    raise exception 'BOOKING_ALLOWED_ONLY_FOR_FLOOR_2' using errcode = 'P0001';
  end if;

  if p_start_time <= now() then
    raise exception 'START_TIME_MUST_BE_IN_THE_FUTURE' using errcode = 'P0001';
  end if;

  select user_id into v_owner
  from public.vehicle_registrations
  where id = p_vehicle_id;

  if v_owner is distinct from v_user_id then
    raise exception 'VEHICLE_NOT_OWNED_BY_USER' using errcode = 'P0001';
  end if;

  select count(*)
  into v_conflict_count
  from public.bookings
  where floor_no = p_floor_no
    and slot = p_slot
    and status in ('booked', 'checked_in')
    and p_start_time < end_time
    and p_end_time > start_time;

  if v_conflict_count > 0 then
    raise exception 'SLOT_ALREADY_BOOKED' using errcode = 'P0001';
  end if;

  insert into public.bookings (
    user_id,
    vehicle_id,
    floor_no,
    slot,
    start_time,
    end_time
  )
  values (
    v_user_id,
    p_vehicle_id,
    p_floor_no,
    p_slot,
    p_start_time,
    p_end_time
  )
  returning * into v_booking;

  return v_booking;
end;
$$;

grant execute on function public.create_booking(uuid, int, int, timestamptz, timestamptz)
  to authenticated;

-- =========================
-- BARRIER / CAMERA VALIDATION
-- Camera sends plate number + current floor/slot
-- Barrier opens only if:
-- 1. plate belongs to a user
-- 2. booking is on floor 2
-- 3. slot matches
-- 4. current time is inside booking window
-- =========================

create or replace function public.validate_barrier_entry(
  p_plate_number text,
  p_floor_no int,
  p_slot int,
  p_check_time timestamptz default now()
)
returns table (
  allowed boolean,
  reason text,
  booking_id uuid,
  user_id uuid
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_booking public.bookings;
begin
  if p_floor_no <> 2 then
    return query select false, 'BARRIER_ONLY_FOR_FLOOR_2', null::uuid, null::uuid;
    return;
  end if;

  select b.*
  into v_booking
  from public.bookings b
  join public.vehicle_registrations v on v.id = b.vehicle_id
  where upper(v.plate_number) = upper(trim(p_plate_number))
    and b.floor_no = p_floor_no
    and b.slot = p_slot
    and b.status in ('booked', 'checked_in')
    and p_check_time >= b.start_time
    and p_check_time <= b.end_time
  order by b.start_time asc
  limit 1;

  if not found then
    return query select false, 'NO_VALID_BOOKING', null::uuid, null::uuid;
    return;
  end if;

  if v_booking.status = 'booked' then
    update public.bookings
    set status = 'checked_in'
    where id = v_booking.id;
  end if;

  return query select true, 'ALLOW', v_booking.id, v_booking.user_id;
end;
$$;

